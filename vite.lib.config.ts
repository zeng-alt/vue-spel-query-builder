import { fileURLToPath, URL } from 'node:url'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, extname, join } from 'node:path'
import { defineConfig, type Plugin, type ResolvedConfig } from 'vite'
import vue from '@vitejs/plugin-vue'
import vueJsx from '@vitejs/plugin-vue-jsx'
import Components from 'unplugin-vue-components/vite'
import { NaiveUiResolver } from 'unplugin-vue-components/resolvers'
import { createGenerator } from 'unocss'
import dts from 'vite-plugin-dts'
import unoConfig from './uno.config'

const UNO_MARK = '/* ===== generated by unocss ===== */'

async function collectSourceFiles(dir: string, out: string[] = []): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const file = join(dir, entry.name)
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '__tests__') continue
      await collectSourceFiles(file, out)
    } else if (entry.isFile() && ['.vue', '.ts'].includes(extname(entry.name))) {
      out.push(file)
    }
  }
  return out
}

/**
 * UnoCSS 在 Vite 8 (rolldown) 的 library 模式下无法通过官方插件注入工具类样式
 * （CSS 资产在 generateBundle 之后才产出）。这里用 UnoCSS 编程式 API 扫描 src
 * 下的全部源码，生成工具类 + preflight CSS，在构建写入完成后合并进唯一产物 CSS。
 */
function unoLibCss(): Plugin {
  let config: ResolvedConfig

  return {
    name: 'unocss:lib-css',
    apply: 'build',
    configResolved(resolved) {
      config = resolved
    },
    async closeBundle() {
      const cssFile = join(config.build.outDir, 'assets', 'vue-spel-query-builder.css')
      try {
        const existing = await readFile(cssFile, 'utf-8')
        if (existing.includes(UNO_MARK)) return

        const uno = await createGenerator(unoConfig)
        const tokens = new Set<string>()
        const files = await collectSourceFiles(resolve(__dirname, 'src'))
        for (const file of files) {
          const code = await readFile(file, 'utf-8')
          await uno.applyExtractors(code, undefined, tokens)
        }
        const { css } = await uno.generate(tokens)
        if (!css) return
        await writeFile(cssFile, `${existing}\n${UNO_MARK}\n${css}`, 'utf-8')
      } catch (error) {
        console.error('[unocss:lib-css] failed to inject styles:', error)
      }
    },
  }
}

export default defineConfig({
  plugins: [
    Components({
      dirs: [],
      dts: false,
      resolvers: [NaiveUiResolver()],
    }),
    vue(),
    vueJsx(),
    unoLibCss(),
    dts({
      include: ['src/**/*.ts', 'src/**/*.vue'],
      outDir: 'dist',
      insertTypesEntry: true,
      rollupTypes: false,
      tsconfigPath: './tsconfig.lib.json',
    }),
  ],
  publicDir: false,
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  build: {
    lib: {
      entry: resolve(__dirname, 'src/index.ts'),
      name: 'VueSpelQueryBuilder',
      formats: ['es', 'cjs'],
      fileName: (format) => `index.${format === 'es' ? 'mjs' : 'cjs'}`,
    },
    rollupOptions: {
      external: ['vue', 'naive-ui', '@codemirror/view', '@codemirror/state', '@codemirror/commands', '@codemirror/autocomplete', '@codemirror/language', 'spel2js', '@lezer/highlight'],
      output: {
        globals: {
          vue: 'Vue',
          'naive-ui': 'naive-ui',
        },
        assetFileNames: 'assets/vue-spel-query-builder[extname]',
      },
    },
    cssCodeSplit: false,
    minify: false,
    sourcemap: true,
  },
})
